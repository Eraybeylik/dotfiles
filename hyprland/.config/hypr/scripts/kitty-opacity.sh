#!/usr/bin/env bash
# Pick the lowest kitty background_opacity that keeps text readable on the
# current wallpaper (WCAG contrast >= 4.5 against its bright regions), so dark
# wallpapers stay see-through and bright ones get a denser terminal.
# Writes ~/.config/kitty/opacity.conf (included by kitty.conf), reloads kitty.
set -uo pipefail

WALL_FILE="$HOME/.cache/last_wallpaper"
KITTY_DIR="$HOME/.config/kitty"
OUT="$KITTY_DIR/opacity.conf"

[[ -f "$WALL_FILE" ]] || exit 0
wallpaper=$(<"$WALL_FILE")
[[ -f "$wallpaper" ]] || exit 0

bg=$(awk '$1=="background"{print $2}' "$KITTY_DIR/colors.conf")
fg=$(awk '$1=="foreground"{print $2}' "$KITTY_DIR/colors.conf")
[[ -n "$bg" && -n "$fg" ]] || exit 0

opacity=$(magick "${wallpaper}[0]" -resize 48x48! -depth 8 rgb:- 2>/dev/null |
  python3 -c '
import sys
bg, fg = sys.argv[1], sys.argv[2]
hexrgb = lambda h: tuple(int(h.lstrip("#")[i:i+2], 16) for i in (0, 2, 4))
def lin(c):
    c /= 255
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
lum = lambda p: 0.2126 * lin(p[0]) + 0.7152 * lin(p[1]) + 0.0722 * lin(p[2])
def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)
data = sys.stdin.buffer.read()
px = sorted((tuple(data[i:i+3]) for i in range(0, len(data) - 2, 3)), key=lum)
if not px:
    print("0.50"); sys.exit()
bright = px[int(len(px) * 0.8)]
tint, text = hexrgb(bg), hexrgb(fg)
for step in range(40, 81, 2):
    o = step / 100
    eff = tuple((1 - o) * bright[i] + o * tint[i] for i in range(3))
    if contrast(text, tuple(int(x) for x in eff)) >= 4.5:
        print(f"{o:.2f}"); break
else:
    print("0.80")
' "$bg" "$fg")

[[ -n "$opacity" ]] || exit 0
printf '# generated by kitty-opacity.sh - do not edit\nbackground_opacity %s\n' "$opacity" > "$OUT"
pkill -USR1 kitty || true
echo "kitty background_opacity -> $opacity"
